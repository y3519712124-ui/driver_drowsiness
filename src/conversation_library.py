    def pick(self, category: str, factors: list[str] | None = None):
        """随机选取一条对话模板，避免重复最近用过的。"""
        pool = getattr(self, category.upper(), self.OBSERVATIONS)
        if not pool:
            pool = self.OBSERVATIONS

        # 排除最近用过的
        available = [t for i, t in enumerate(pool) if i not in self._history]
        if not available:
            self._history.clear()
            available = pool

        text = random.choice(available)
        idx = pool.index(text)
        self._history.append(idx)

        # 限制历史长度
        from config import TEMPLATE_HISTORY_SIZE
        if len(self._history) > TEMPLATE_HISTORY_SIZE:
            self._history = self._history[-TEMPLATE_HISTORY_SIZE:]

        return text
